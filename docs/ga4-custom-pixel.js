/*
  GA4 custom pixel for Belle's Performance Tennis Shop
  ----------------------------------------------------
  WHERE THIS GOES: this is NOT theme code. Do not put it in the theme.

    Shopify Admin -> Settings -> Customer events -> Add custom pixel
    Name it "Calendly booking events", paste this in, Save, then Connect.

  WHY IT IS NEEDED: snippets/calendly-modal.liquid publishes two events with
  Shopify.analytics.publish(). Publishing alone does not reach GA4. A pixel
  has to subscribe to them and forward them on. Until this pixel exists, the
  theme is emitting into the void.

  WHY IT LOADS ITS OWN gtag: Shopify custom pixels run in a sandboxed frame
  with no access to the page's own analytics, and this store loads GA4
  through the Google channel rather than a theme snippet, so window.gtag
  does not exist in page context either. The pixel therefore loads its own
  copy inside its own sandbox.

  send_page_view is false ON PURPOSE. The Google channel already reports
  pageviews for G-SKJK8YPREK. Leaving it on would double count every one.
  This pixel should only ever send the two Calendly events.

  EXPECTED WARNING, DO NOT "FIX" IT BY DELETING THIS PIXEL
  --------------------------------------------------------
  Google Tag Manager's Tag Diagnostics reports:

    "Unsupported tag implementation detected on Shopify. Your Google tag
     is running in a Shopify custom pixel. This may create duplicate
     measurement with your Google tag configured in the Google & YouTube
     app on your Shopify website."

  That warning fires on the PATTERN, not on observed duplication. Seen and
  assessed 2026-09-07. It is expected here and was accepted knowingly:

  1. No event is sent twice. The Google channel sends page_view,
     session_start, first_visit, scroll and ecommerce. This pixel sends
     only the two calendly_* events, and send_page_view is off. The two
     sets are disjoint.

  2. The real residual risk is attribution, not duplication. Two gtag
     instances on one measurement ID sit in separate storage contexts, and
     a Shopify pixel sandbox may not share the _ga cookie. The Calendly
     events can therefore land against a different client ID or session
     than the pageviews, which would weaken GA4 path and attribution
     reports.

  3. That risk is mitigated in the payload rather than the plumbing.
     booking_source and page_path are sent as explicit event parameters,
     so "which page and which button produced this booking" is answerable
     from the event itself, with no session stitching required. This is
     why those parameters exist. Do not drop them.

  Why not avoid the warning entirely: window.gtag does not exist in this
  store's page context, so theme code has no tag to talk to. Putting gtag
  in theme.liquid would break the performance rules in CLAUDE.md AND cause
  genuine duplication. Measurement Protocol would need a secret embedded
  in client-visible code and loses client linkage anyway. A custom pixel
  loading its own gtag is the least-bad option, and Google documents it as
  a supported way to send events even while flagging the pattern.

  Events forwarded:
    calendly_modal_open       someone opened the booking modal (intent)
    calendly_event_scheduled  Calendly confirmed a booking  (THE CONVERSION)

  Both carry:
    booking_source  from utm_content on the CTA that was clicked, so you can
                    tell the homepage hero from a city page from the blog
    page_path       the page the visitor was on

  AFTER CONNECTING, in GA4: Admin -> Events -> mark calendly_event_scheduled
  as a key event, otherwise it will not appear in conversion reporting.
*/

const MEASUREMENT_ID = 'G-SKJK8YPREK';

// Load gtag inside this pixel's sandbox
const s = document.createElement('script');
s.async = true;
s.src = 'https://www.googletagmanager.com/gtag/js?id=' + MEASUREMENT_ID;
document.head.appendChild(s);

window.dataLayer = window.dataLayer || [];
function gtag() { window.dataLayer.push(arguments); }
gtag('js', new Date());
gtag('config', MEASUREMENT_ID, { send_page_view: false });

/*
  The two subscriptions below are deliberately written out in full rather
  than generated by a helper.

  Shopify statically scans pasted pixel code for analytics.subscribe() with
  a LITERAL event name, and uses that to decide which events the pixel is
  subscribed to. An earlier version of this file looped over the names via
  a helper function, passing the name as a variable. It was valid
  JavaScript and would have run, but the scanner could not see any literal
  names, so the editor showed:

    "Pixel will not track any customer behavior because it is not
     subscribed to any events."

  Keep both calls inline with quoted event names. Do not refactor these
  into a loop or a helper, however repetitive it looks.
*/

analytics.subscribe('calendly_modal_open', (event) => {
  const d = (event && event.customData) || {};
  gtag('event', 'calendly_modal_open', {
    booking_source: d.booking_source || 'unknown',
    page_path: d.page_path || ''
  });
});

analytics.subscribe('calendly_event_scheduled', (event) => {
  const d = (event && event.customData) || {};
  gtag('event', 'calendly_event_scheduled', {
    booking_source: d.booking_source || 'unknown',
    page_path: d.page_path || ''
  });
});
