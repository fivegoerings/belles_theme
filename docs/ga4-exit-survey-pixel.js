/*
  GA4 custom pixel for Belle's Performance Tennis Shop, exit-intent survey.

  WHERE THIS GOES: this is NOT theme code. Do not put it in the theme.

    Shopify Admin -> Settings -> Customer events -> Add custom pixel
    Name it "Exit survey events", paste this in, Save, then Connect.

  THIS IS A NEW, SEPARATE PIXEL, NOT A REVIVAL OF docs/ga4-custom-pixel.js.
  That earlier pixel (forwarding calendly_modal_open/calendly_event_scheduled)
  was removed 2026-09-16 because it duplicated measurement, and its own
  comments say "do not re-add". This pixel only subscribes to the three
  exit_survey_* events below, which have no other reporting path at all (no
  Shopify Web Pixel automatically covers them, unlike pageviews/ecommerce).
  Approved by the site owner 2026-09-24 specifically for these events. If
  the old pixel is ever reconnected for the calendly events, keep the two
  pixels separate rather than merging them, so either can be disconnected
  independently.

  WHY IT LOADS ITS OWN gtag: Shopify custom pixels run in a sandboxed frame
  with no access to the page's own analytics, and this store loads GA4
  through the Google channel rather than a theme snippet, so window.gtag
  does not exist in page context for GA4 either (the theme's own gtag
  instance in layout/theme.liquid is Ads-only, see CLAUDE.md). The pixel
  therefore loads its own copy inside its own sandbox, same pattern as the
  historical pixel.

  send_page_view is false ON PURPOSE. The Google channel already reports
  pageviews for G-SKJK8YPREK. Leaving it on would double count every one.
  This pixel should only ever send the three exit_survey_* events.

  EXPECTED WARNING, DO NOT "FIX" IT BY DELETING THIS PIXEL
  --------------------------------------------------------
  Google Tag Manager's Tag Diagnostics will report:

    "Unsupported tag implementation detected on Shopify. Your Google tag
     is running in a Shopify custom pixel. This may create duplicate
     measurement with your Google tag configured in the Google & YouTube
     app on your Shopify website."

  That warning fires on the PATTERN, not on observed duplication, same as
  it did for the historical pixel (see docs/ga4-custom-pixel.js for the full
  reasoning). It applies here too and is accepted for the same reasons:
  the Google channel's automatic events (page_view, session_start,
  first_visit, scroll, ecommerce) and this pixel's three exit_survey_*
  events are disjoint sets, so nothing is counted twice. The residual risk
  is attribution (these events may land against a different client ID or
  session than the pageviews, since a Shopify pixel sandbox may not share
  the _ga cookie), which is why page_path rides along as an explicit event
  parameter on every event below rather than relying on session stitching.

  Events forwarded (published by snippets/belle-exit-survey.liquid via
  Shopify.analytics.publish):

    exit_survey_shown       the popup displayed (desktop exit-intent, or the
                             mobile fast-scroll-up-near-top heuristic)
    exit_survey_response     a visitor picked a reason, or submitted free
                             text under "Something else"
    exit_survey_dismissed    closed via the X, "No thanks", Escape, or a
                             click on the overlay, without answering

  All three carry page_path. exit_survey_response also carries reason (a
  short slug: price / drop_off_unclear / just_browsing / couldnt_find_info /
  other) and reason_detail (free text, only populated when reason is
  "other").

  AFTER CONNECTING, in GA4 you likely do NOT want to mark any of these as a
  key event/conversion - they're feedback signals, not the booking
  conversion. See CLAUDE.md / belles-ga4-key-events for the events that are
  already marked (purchase, invitee_meeting_scheduled).
*/

const MEASUREMENT_ID = 'G-SKJK8YPREK';

// Load gtag inside this pixel's sandbox
const s = document.createElement('script');
s.async = true;
s.src = 'https://www.googletagmanager.com/gtag/js?id=' + MEASUREMENT_ID;
document.head.appendChild(s);

window.dataLayer = window.dataLayer || [];
function gtag() { window.dataLayer.push(arguments); }
gtag('js', new Date());
gtag('config', MEASUREMENT_ID, { send_page_view: false });

/*
  Shopify statically scans pasted pixel code for analytics.subscribe() with
  a LITERAL event name to decide which events the pixel is subscribed to.
  Keep these three calls inline with quoted event names, not generated by a
  loop or helper - see docs/ga4-custom-pixel.js for what happens otherwise.
*/

analytics.subscribe('exit_survey_shown', (event) => {
  const d = (event && event.customData) || {};
  gtag('event', 'exit_survey_shown', {
    page_path: d.page_path || ''
  });
});

analytics.subscribe('exit_survey_response', (event) => {
  const d = (event && event.customData) || {};
  gtag('event', 'exit_survey_response', {
    reason: d.reason || 'unknown',
    reason_detail: d.reason_detail || '',
    page_path: d.page_path || ''
  });
});

analytics.subscribe('exit_survey_dismissed', (event) => {
  const d = (event && event.customData) || {};
  gtag('event', 'exit_survey_dismissed', {
    page_path: d.page_path || ''
  });
});
